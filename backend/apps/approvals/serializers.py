class AuditLogSerializer(serializers.ModelSerializer):
    """Serializer for immutable approval audit log records."""

    actor_email = serializers.EmailField(source="actor.email", read_only=True, default=None)

    class Meta:
        model = AuditLog
        fields = [
            "id",
            "approval_request",
            "actor",
            "actor_email",
            "action_taken",
            "payload_snapshot",
            "notes",
            "timestamp",
        ]
        read_only_fields = fields


