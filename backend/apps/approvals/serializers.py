class ApprovalDecisionActionSerializer(serializers.Serializer):
    """
    Serializer for validating incoming user decision payloads (Approve / Reject).
    """

    decision = serializers.ChoiceField(
        choices=[(ApprovalStatus.APPROVED, "Approve"), (ApprovalStatus.REJECTED, "Reject")],
        required=True,
        help_text="The decision to apply: 'approved' or 'rejected'.",
    )
    notes = serializers.CharField(
        required=False,
        allow_blank=True,
        default="",
        help_text="Optional feedback or rejection reason explaining the decision.",
    )

    def validate(self, data):
        """Ensure rejection includes a reason when applicable."""
        decision = data.get("decision")
        notes = data.get("notes", "").strip()

        if decision == ApprovalStatus.REJECTED and not notes:
            # Rejection notes are strongly encouraged for audit clarity
            data["notes"] = "Rejected by reviewer without explicit reason."

        return data


class ApprovalRequestCreateSerializer(serializers.ModelSerializer):
    """
    Serializer used internally by Strands SDK / LangGraph nodes to register new HITL checkpoints.
    """

    class Meta:
        model = ApprovalRequest
        fields = [
            "run",
            "risk_level",
            "action_type",
            "action_description",
            "proposed_payload",
            "thread_id",
            "checkpoint_ns",
            "expires_at",
        ]

    def validate_risk_level(self, value):
        if value not in ActionRiskLevel.values:
            raise serializers.ValidationError(f"Invalid risk level '{value}'.")
        return value